import Database from "better-sqlite3";
import { initDatabase, storeEmbedding } from "../../src/db.js";
import {
  embeddingToBuffer,
  generateEmbedding,
  getActiveEmbeddingIdentity,
  getActiveEmbeddingModel,
  getConfiguredEmbeddingIdentity,
  initEmbeddings,
} from "../../src/embeddings.js";

export function ensureSafeGeneratedPath(path: string, label: string): void {
  const normalized = path.replace(/\\/g, "/");
  if (!normalized.includes("/benchmark/generated/")) {
    throw new Error(
      `${label} must live under benchmark/generated/ to avoid accidental writes against live data: ${path}`,
    );
  }
}

export interface CorpusEmbeddingSummary {
  total: number;
  generated: number;
  failed: number;
  skipped: number;
  /** Actual row count in entries_vec — 0 when sqlite-vec is unavailable or the table is empty. */
  vector_rows: number;
}

/**
 * Generate embeddings for every entry in a benchmark DB that does not already
 * have one. Safe to rerun: rows stuck in `processing` from an interrupted run
 * are reset to `pending`. Only vectors with the current model and immutable
 * embedding identity are reused; legacy, stale, or missing vectors are rebuilt.
 */
export async function populateCorpusEmbeddings(dbPath: string): Promise<CorpusEmbeddingSummary> {
  const db: Database.Database = initDatabase(dbPath);
  try {
    const ready = await initEmbeddings();
    if (!ready) {
      throw new Error("Embedding system could not be initialized for hybrid/semantic benchmark run.");
    }

    const activeModel = getActiveEmbeddingModel();
    const activeIdentity = getActiveEmbeddingIdentity();
    if (activeIdentity === null || getConfiguredEmbeddingIdentity() !== activeIdentity) {
      throw new Error("Embedding identity is unavailable or changed after initialization; refusing to populate corpus.");
    }

    const assertConfiguredBindingCurrent = () => {
      if (getActiveEmbeddingModel() !== activeModel || getConfiguredEmbeddingIdentity() !== activeIdentity) {
        throw new Error("Embedding binding changed while populating corpus; refusing to claim a consistent result.");
      }
    };

    // Recover rows left mid-flight by a previous interrupted run.
    db.prepare("UPDATE entries SET embedding_status = 'pending' WHERE embedding_status = 'processing'").run();

    // Select entries that need (re-)embedding:
    //  - not yet generated (pending/failed/processing)
    //  - OR generated by a different model or immutable identity
    //  - OR the vector row is missing despite generated provenance
    const rows = db
      .prepare(
        `WITH vector_ids AS MATERIALIZED (SELECT DISTINCT entry_id FROM entries_vec)
         SELECT e.id, e.content FROM entries e
         LEFT JOIN vector_ids v ON v.entry_id = e.id
         WHERE e.embedding_status != 'generated'
            OR e.embedding_model IS NULL OR e.embedding_model != ?
            OR e.embedding_identity IS NULL OR e.embedding_identity != ?
            OR v.entry_id IS NULL
         ORDER BY e.created_at ASC`,
      )
      .all(activeModel, activeIdentity) as Array<{ id: string; content: string }>;
    const totalRows = db.prepare("SELECT COUNT(*) as cnt FROM entries").get() as { cnt: number };

    let generated = 0;
    let failed = 0;
    const skipped = totalRows.cnt - rows.length;
    const startedAt = Date.now();

    if (skipped > 0) {
      console.log(`Reusing ${skipped} existing embeddings from prior benchmark work.`);
    }

    for (let index = 0; index < rows.length; index += 1) {
      const row = rows[index];
      assertConfiguredBindingCurrent();
      const embedding = await generateEmbedding(row.content);
      assertConfiguredBindingCurrent();
      if (!embedding) {
        db.prepare("UPDATE entries SET embedding_status = 'failed' WHERE id = ?").run(row.id);
        failed += 1;
        continue;
      }
      if (getActiveEmbeddingIdentity() !== activeIdentity) {
        throw new Error("Embedding binding changed while populating corpus; refusing to store an unbound vector.");
      }
      storeEmbedding(
        db,
        row.id,
        embeddingToBuffer(embedding),
        activeModel,
        activeIdentity,
      );
      generated += 1;

      const processed = index + 1;
      if (processed % 250 === 0 || processed === rows.length) {
        const elapsedSeconds = Math.max((Date.now() - startedAt) / 1000, 1);
        const rate = processed / elapsedSeconds;
        console.log(
          `Embedding progress: ${processed}/${rows.length} pending rows processed (${generated} generated, ${failed} failed, ${rate.toFixed(1)} rows/s)`,
        );
      }
    }

    assertConfiguredBindingCurrent();

    let vectorRows = 0;
    try {
      vectorRows = (db.prepare("SELECT COUNT(*) AS c FROM entries_vec").get() as { c: number }).c;
    } catch {
      vectorRows = 0;
    }

    return { total: totalRows.cnt, generated, failed, skipped, vector_rows: vectorRows };
  } finally {
    db.close();
  }
}
